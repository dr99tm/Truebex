<#
.SYNOPSIS
    Regenerate openapi/clients.json and the two light clients generated from it (PF10).

.DESCRIPTION
    1. server\scripts\export_openapi.py --clients     -> openapi/clients.json (the routes PF9 and PF10 call)
    2. openapi-typescript (MIT, pinned)               -> src/lib/api-clients.d.ts (PF9's TypeScript types)
    3. OpenAPI Generator, dart (Apache-2.0, pinned)   -> mobile/android/lib/api/gen/ (PF10's Dart client)
    The generator jar is downloaded once into mobile\.tools\ (git-ignored) and checked against its
    Maven Central SHA-1; it runs on the JDK of JAVA_HOME, Android Studio or PATH.
    Both outputs carry the document's SHA-256; server/tests/test_pf10_clients.py fails when
    either is older than openapi/clients.json, or when the document is older than the routes.
    Commit what changed.
#>
[CmdletBinding()]
param()
$ErrorActionPreference = 'Stop'
$Root = Split-Path -Parent $PSScriptRoot
Set-Location $Root
$env:PYTHONUTF8 = '1'

$OpenApiTypescript = 'openapi-typescript@7.13.0'
$GeneratorVersion = '7.26.0'
$GeneratorSha1 = 'b96b148fcf482808037f68fbad99cb4d7e65d40b'

function Run($what, [scriptblock]$body) {
    Write-Host "=== $what ==="
    & $body
    if ($LASTEXITCODE -ne 0) { throw "$what failed ($LASTEXITCODE)" }
}

function Find-Java {
    $candidates = @()
    if ($env:JAVA_HOME) { $candidates += (Join-Path $env:JAVA_HOME 'bin\java.exe') }
    $candidates += 'C:\Program Files\Android\Android Studio\jbr\bin\java.exe'
    $onPath = Get-Command java -ErrorAction SilentlyContinue
    if ($onPath) { $candidates += $onPath.Source }
    foreach ($c in $candidates) { if ($c -and (Test-Path $c)) { return $c } }
    throw 'No Java runtime (17 or newer): set JAVA_HOME or install Android Studio (GD4).'
}

$ServerPy = Join-Path $Root 'server\.venv\Scripts\python.exe'
if (-not (Test-Path $ServerPy)) { throw 'server\.venv is missing: run scripts\autopilot-setup.ps1 (or make the venv) first' }
Run 'export openapi/clients.json' { & $ServerPy server\scripts\export_openapi.py --clients }
$Doc = Join-Path $Root 'openapi\clients.json'
# Of the text with LF line ends, so a CRLF checkout hashes the same (tests/test_pf10_clients.py).
$Sha = (& $ServerPy -c "import hashlib,sys; print(hashlib.sha256(open(sys.argv[1],'rb').read().replace(b'\r\n',b'\n')).hexdigest())" $Doc).Trim()

# --- PF9: TypeScript types ------------------------------------------------------------------
$Dts = Join-Path $Root 'src\lib\api-clients.d.ts'
Run 'typescript types' { & npx --yes $OpenApiTypescript openapi/clients.json --default-non-nullable=false -o $Dts }
$body = [IO.File]::ReadAllText($Dts)
$head = "// Generated by scripts/gen-clients.ps1 from openapi/clients.json (sha256 $Sha). Do not edit.`n"
[IO.File]::WriteAllText($Dts, $head + $body, (New-Object Text.UTF8Encoding $false))

# --- PF10: the Dart client ------------------------------------------------------------------
$Tools = Join-Path $Root 'mobile\.tools'
New-Item -ItemType Directory -Force $Tools | Out-Null
$Jar = Join-Path $Tools "openapi-generator-cli-$GeneratorVersion.jar"
if (-not (Test-Path $Jar)) {
    $url = "https://repo1.maven.org/maven2/org/openapitools/openapi-generator-cli/$GeneratorVersion/openapi-generator-cli-$GeneratorVersion.jar"
    Write-Host "downloading $url"
    Invoke-WebRequest -Uri $url -OutFile "$Jar.part" -UseBasicParsing
    Move-Item -Force "$Jar.part" $Jar
}
$got = (Get-FileHash $Jar -Algorithm SHA1).Hash.ToLowerInvariant()
if ($got -ne $GeneratorSha1) { Remove-Item $Jar; throw "openapi-generator jar SHA-1 $got, expected $GeneratorSha1" }
$Java = Find-Java
$Tmp = Join-Path $Tools 'dart-out'
if (Test-Path $Tmp) { Remove-Item -Recurse -Force $Tmp }
Run 'dart client' {
    & $Java -jar $Jar generate -i $Doc -g dart -o $Tmp --global-property 'apiDocs=false,modelDocs=false,apiTests=false,modelTests=false' `
        --additional-properties 'pubName=truebex_api,pubLibrary=truebex.api,pubVersion=1.0.0,pubDescription=Generated from openapi/clients.json' `
        --skip-validate-spec 2>&1 | Where-Object { $_ -notmatch '\[main\] INFO' }
}
$Gen = Join-Path $Root 'mobile\android\lib\api\gen'
if (Test-Path $Gen) { Remove-Item -Recurse -Force $Gen }
Copy-Item -Recurse (Join-Path $Tmp 'lib') $Gen
Copy-Item (Join-Path $Tmp '.openapi-generator\VERSION') (Join-Path $Gen 'GENERATOR_VERSION')
[IO.File]::WriteAllText((Join-Path $Gen 'SPEC_SHA256'), "$Sha`n", (New-Object Text.UTF8Encoding $false))
Remove-Item -Recurse -Force $Tmp
Write-Host "clients regenerated from openapi/clients.json ($Sha). Review and commit openapi/, src/lib/api-clients.d.ts, mobile/android/lib/api/gen/."
