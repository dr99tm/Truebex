"""Generate the SDKs' operation layer from `openapi/v1.json` (PF12).

    python sdks/generate.py            write the files below
    python sdks/generate.py --check    exit 1 when one differs (tests run this)

Writes, for every operation of the document (its id is `<group>_<method>`):
* `sdks/python/truebex/_operations.py`: a class per group with a typed method
  per operation (path parameters positional, the JSON body's properties, the
  query and the idempotency key as keywords), returning `models.<Schema>`.
* `sdks/js/src/operations.mjs` and `operations.d.ts`: the same table for the
  fetch client, typed against `schema.d.ts`.

The types themselves come from MIT generators (scripts/gen-sdks.ps1):
datamodel-code-generator writes `truebex/models.py`, openapi-typescript
writes `schema.d.ts`. Standard library only, Python 3.11+.
"""

import argparse
import json
import keyword
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "openapi" / "v1.json"
PY_OUT = ROOT / "sdks" / "python" / "truebex" / "_operations.py"
JS_OUT = ROOT / "sdks" / "js" / "src" / "operations.mjs"
DTS_OUT = ROOT / "sdks" / "js" / "src" / "operations.d.ts"
GROUP_ORDER = ("account", "projects", "jobs", "uploads", "shares", "market", "feeds", "webhooks")
HEADER_ARGS = {"idempotency-key": "idempotency_key", "x-part-sha256": "part_sha256"}
NOTICE = "Generated by sdks/generate.py from openapi/v1.json. Do not edit."


def _camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(p[:1].upper() + p[1:] for p in rest)


def _pascal(name: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in name.split("_"))


def _py_name(name: str) -> str:
    name = re.sub(r"\W", "_", name)
    return name + "_" if keyword.iskeyword(name) else name


class Doc:
    def __init__(self, doc: dict) -> None:
        self.doc = doc
        self.schemas = doc["components"]["schemas"]

    def resolve(self, schema: dict) -> dict:
        while "$ref" in schema:
            schema = self.schemas[schema["$ref"].rsplit("/", 1)[1]]
        return schema

    def py_type(self, schema: dict) -> str:
        if "$ref" in schema:
            return "models." + schema["$ref"].rsplit("/", 1)[1]
        if "anyOf" in schema:
            parts = [self.py_type(s) for s in schema["anyOf"]]
            return " | ".join(dict.fromkeys(parts))
        if "enum" in schema:
            return "Literal[" + ", ".join(json.dumps(v) for v in schema["enum"]) + "]"
        kind = schema.get("type")
        if kind == "array":
            return f"list[{self.py_type(schema.get('items', {}))}]"
        return {
            "string": "str",
            "integer": "int",
            "number": "float",
            "boolean": "bool",
            "null": "None",
            "object": "dict[str, Any]",
        }.get(kind, "Any")

    def operations(self) -> list[dict]:
        ops = []
        for path, item in self.doc["paths"].items():
            for method, op in item.items():
                group, action = op["operationId"].split("_", 1)
                params = op.get("parameters", [])
                path_params = re.findall(r"\{(\w+)\}", path)
                path_types = {p["name"]: p.get("schema", {}) for p in params if p["in"] == "path"}
                query = [p for p in params if p["in"] == "query"]
                headers = [p["name"].lower() for p in params if p["in"] == "header" and p["name"].lower() in HEADER_ARGS]
                body_kind, body_props, body_ref = None, [], None
                content = (op.get("requestBody") or {}).get("content", {})
                if "application/json" in content:
                    body_kind = "json"
                    ref = content["application/json"]["schema"]
                    body_ref = ref["$ref"].rsplit("/", 1)[1] if "$ref" in ref else None
                    resolved = self.resolve(ref)
                    required = set(resolved.get("required", []))
                    for name, prop in resolved.get("properties", {}).items():
                        body_props.append({"name": name, "schema": prop, "required": name in required})
                elif "application/octet-stream" in content:
                    body_kind = "binary"
                elif "multipart/form-data" in content:
                    body_kind = "multipart"
                    ref = content["multipart/form-data"]["schema"]
                    body_ref = ref["$ref"].rsplit("/", 1)[1] if "$ref" in ref else None
                    resolved = self.resolve(ref)
                    required = set(resolved.get("required", []))
                    for name, prop in resolved.get("properties", {}).items():
                        body_props.append({"name": name, "schema": prop, "required": name in required})
                status, returns = None, None
                for code in sorted(op["responses"]):
                    if code.startswith("2"):
                        status = code
                        schema = op["responses"][code].get("content", {}).get("application/json", {}).get("schema")
                        returns = schema["$ref"].rsplit("/", 1)[1] if schema and "$ref" in schema else None
                        break
                ops.append(
                    {
                        "id": op["operationId"],
                        "group": group,
                        "action": action,
                        "method": method.upper(),
                        "path": path,
                        "path_params": path_params,
                        "path_types": path_types,
                        "query": [{"name": q["name"], "schema": q.get("schema", {}), "required": q.get("required", False)} for q in query],
                        "headers": headers,
                        "body_kind": body_kind,
                        "body_props": body_props,
                        "body_ref": body_ref,
                        "status": status,
                        "returns": returns,
                        "scope": op.get("x-truebex-scope"),
                        "optional_key": op.get("x-truebex-auth") == "optional",
                        "contract": op.get("x-truebex-contract"),
                        "summary": (op.get("description") or op.get("summary") or "").strip(),
                    }
                )
        order = {g: i for i, g in enumerate(GROUP_ORDER)}
        ops.sort(key=lambda o: (order.get(o["group"], 99), o["id"]))
        return ops


# --- Python -----------------------------------------------------------------------------------


def _optional(ann: str) -> str:
    return ann if ann == "None" or ann.endswith("| None") else f"{ann} | None"


def _py_doc(op: dict) -> str:
    lines = [op["summary"] or op["id"], ""]
    scope = op["scope"] or "any key"
    lines.append(f"{op['method']} {op['path']} · scope: {scope}" + (" (a key is optional)" if op["optional_key"] else ""))
    return "\n".join(lines)


def python(doc: Doc) -> str:
    ops = doc.operations()
    out = [
        f'"""{NOTICE}"""',
        "",
        "# ruff: noqa",
        "from __future__ import annotations",
        "",
        "from typing import TYPE_CHECKING, Any, Literal",
        "",
        "from ._http import UNSET, Resource",
        "",
        "if TYPE_CHECKING:",
        "    from . import models",
        "",
        "OPERATIONS: dict[str, dict[str, Any]] = {",
    ]
    for op in ops:
        meta = {
            "method": op["method"],
            "path": op["path"],
            "path_params": op["path_params"],
            "query": [q["name"] for q in op["query"]],
            "headers": op["headers"],
            "body": op["body_kind"],
            "body_props": [p["name"] for p in op["body_props"]],
            "scope": op["scope"],
            "contract": op["contract"],
        }
        out.append(f"    {op['id']!r}: {meta!r},")
    out += ["}", ""]
    groups: dict[str, list[dict]] = {}
    for op in ops:
        groups.setdefault(op["group"], []).append(op)
    for group, items in groups.items():
        out += ["", f"class {_pascal(group)}(Resource):", f'    """The `{group}` operations."""', ""]
        for op in items:
            args = ["self"] + [
                f"{_py_name(p)}: {doc.py_type(op['path_types'].get(p, {'type': 'string'}))}" for p in op["path_params"]
            ]
            kw: list[str] = []
            call_kw: list[str] = []
            if op["body_kind"] == "binary":
                args.append("data: bytes")
                call_kw.append("data=data")
            required_kw, optional_kw = [], []
            for prop in op["body_props"]:
                name = _py_name(prop["name"])
                ann = "bytes" if (op["body_kind"] == "multipart" and prop["name"] == "file") else doc.py_type(prop["schema"])
                (required_kw if prop["required"] else optional_kw).append(
                    f"{name}: {ann}" if prop["required"] else f"{name}: {_optional(ann)} = UNSET"
                )
            for q in op["query"]:
                name = _py_name(q["name"])
                ann = doc.py_type(q["schema"])
                (required_kw if q["required"] else optional_kw).append(
                    f"{name}: {ann}" if q["required"] else f"{name}: {_optional(ann)} = UNSET"
                )
            if op["body_kind"] == "multipart":
                optional_kw.append('filename: str = "feed"')
            for h in op["headers"]:
                optional_kw.append(f"{HEADER_ARGS[h]}: str | None = None")
            kw = required_kw + optional_kw
            if kw:
                args.append("*")
                args += kw
            ret = f"models.{op['returns']}" if op["returns"] else ("None" if op["status"] == "204" else "Any")
            out.append(f"    def {_py_name(op['action'])}({', '.join(args)}) -> {ret}:")
            first, *more = _py_doc(op).split("\n")
            out.append('        """' + "\n".join([first] + [("        " + ln).rstrip() for ln in more]) + '"""')
            pieces = [repr(op["id"])]
            pieces += [_py_name(p) for p in op["path_params"]]
            values = [f"{p['name']!r}: {_py_name(p['name'])}" for p in op["body_props"]]
            values += [f"{q['name']!r}: {_py_name(q['name'])}" for q in op["query"]]
            if values:
                call_kw.append("values={" + ", ".join(values) + "}")
            for h in op["headers"]:
                call_kw.append(f"{HEADER_ARGS[h]}={HEADER_ARGS[h]}")
            if op["body_kind"] == "multipart":
                call_kw.append("filename=filename")
            out.append(f"        return self._call({', '.join(pieces + call_kw)})")
            out.append("")
    out += ["", "GROUPS = {" + ", ".join(f"{g!r}: {_pascal(g)}" for g in groups) + "}", ""]
    return "\n".join(out)


# --- JavaScript ---------------------------------------------------------------------------------


def js(doc: Doc) -> str:
    ops = doc.operations()
    table = {}
    for op in ops:
        table[op["id"]] = {
            "group": op["group"],
            "name": _camel(op["action"]),
            "method": op["method"],
            "path": op["path"],
            "pathParams": op["path_params"],
            "query": [q["name"] for q in op["query"]],
            "headers": op["headers"],
            "body": op["body_kind"],
            "bodyProps": [p["name"] for p in op["body_props"]],
            "scope": op["scope"],
            "contract": op["contract"],
        }
    return (
        f"// {NOTICE}\n\n"
        "/** Every operation of the developer API, by operation id. */\n"
        f"export const OPERATIONS = {json.dumps(table, indent=2)};\n"
    )


def _ts_schema(name: str | None) -> str:
    return f'components["schemas"]["{name}"]' if name else "unknown"


def dts(doc: Doc) -> str:
    ops = doc.operations()
    groups: dict[str, list[dict]] = {}
    for op in ops:
        groups.setdefault(op["group"], []).append(op)
    out = [
        f"// {NOTICE}",
        "",
        'import type { components, operations } from "./schema";',
        "",
        "/** Options every call takes. */",
        "export interface CallOptions {",
        "  /** 32 hex; the SDK makes one for operations that take it. */",
        "  idempotencyKey?: string;",
        "  signal?: AbortSignal;",
        "}",
        "",
        "export declare const OPERATIONS: Record<string, unknown>;",
        "",
    ]
    for group, items in groups.items():
        out.append(f"export interface {_pascal(group)}Api {{")
        for op in items:
            params = [
                f"{_camel(p)}: {'number' if op['path_types'].get(p, {}).get('type') == 'integer' else 'string'}"
                for p in op["path_params"]
            ]
            if op["body_kind"] == "binary":
                params.append("data: Uint8Array | ArrayBuffer | Blob")
            fields = []
            if op["body_kind"] == "json" and op["body_ref"]:
                fields.append(_ts_schema(op["body_ref"]))
            elif op["body_kind"] == "multipart":
                fields.append(
                    "{ file: Blob | Uint8Array | string; filename?: string; format: \"csv\" | \"json\"; mode?: \"upsert\" | \"replace\" }"
                )
            if op["query"]:
                fields.append(f'NonNullable<operations["{op["id"]}"]["parameters"]["query"]>')
            if op["headers"] and "x-part-sha256" in op["headers"]:
                fields.append("{ partSha256?: string }")
            ret = _ts_schema(op["returns"]) if op["returns"] else ("void" if op["status"] == "204" else "unknown")
            arg = " & ".join(fields) if fields else None
            required = any(p["required"] for p in op["body_props"]) or any(q["required"] for q in op["query"])
            if arg:
                params.append(f"params{'' if required else '?'}: {arg}")
            params.append("options?: CallOptions")
            out.append(f"  /** {op['summary'].splitlines()[0] if op['summary'] else op['id']} ({op['method']} {op['path']}; scope {op['scope'] or 'any key'}) */")
            out.append(f"  {_camel(op['action'])}({', '.join(params)}): Promise<{ret}>;")
        out.append("}")
        out.append("")
    return "\n".join(out)


def outputs() -> dict[Path, str]:
    doc = Doc(json.loads(DOC.read_text(encoding="utf-8")))
    return {PY_OUT: python(doc), JS_OUT: js(doc), DTS_OUT: dts(doc)}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Generate the SDKs' operation layer from openapi/v1.json.")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    stale = []
    for path, text in outputs().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("out of date (run python sdks/generate.py): " + ", ".join(str(p.relative_to(ROOT)) for p in stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
